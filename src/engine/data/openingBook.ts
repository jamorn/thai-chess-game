// src/engine/data/openingBook.ts
// ===========================================================================
//  Opening Book — สมุดเปิดหมากสำหรับหมากรุกไทย
//  ----------------------------------------------------------------
//  อ้างอิง: "หลักการเปิดเกมหมากรุกไทย 10 ประการ โดยครูพงษ์"
//  (ดู Docs/OPENING_BOOK.MD)
//
//  - ข้อ 1-4 ที่เป็น "ตำแหน่งการเปิด" นำมาสร้างเป็น BOOK นี้
//  - ใช้ Weighted Random เพื่อให้ AI ตอบโต้เร็ว (~0ms) และไม่ซ้ำเดิมทุกเกม
//
//  พิกัด (Row/Col 0-indexed):
//    Row 0 = แถวดำ, Row 7 = แถวแดง
//    'ง2' ฝั่งแดง = [row 5, col 2] · ฝั่งดำ = [row 2, col 2]
// ===========================================================================

export interface BookMove {
  /** พิกัดต้นทาง [row, col] 0-indexed */
  from: [number, number];
  /** พิกัดปลายทาง [row, col] 0-indexed */
  to: [number, number];
  /** น้ำหนักความถี่ที่สุ่มเลือก (ยิ่งมากยิ่งมีโอกาสถูกเลือกสูง) */
  weight: number;
}

export interface BookNode {
  /** รายการตาเดินแนะนำในสถานะนี้ (ถ่วงน้ำหนัก) */
  moves: BookMove[];
}

